//! The eboot's EffectQuake, update by update: effect_quake_a (0x810089a4)
//! starts the record, effect_quake_b (0x81008a3c) moves the screen each
//! update. Checked against the eboot run under exe_call
//! (research/oretsuba/quake_exe.py, the test's `EBOOT_QUAKE`).

/// The path the table shake follows (0x81161fb0: x then y, eleven each;
/// the last pair is never read, the index wraps at 10), ±100 = `:Param`'s
/// size.
const PATH_X: [i32; 11] = [0, 100, -100, -100, 0, 100, 0, -100, 100, 100, 0];
const PATH_Y: [i32; 11] = [0, 100, -100, 0, 100, 0, -100, 100, -100, 100, 0];

/// An EffectQuake as scene_load case 99 (0x8102840a) starts it: `time`
/// updates (`:Time`, made positive), `fade` (`:Time` with `:Fade 1`, else
/// 0: dies down linearly over that many updates, then stops), `looped`
/// (`:Loop 1`, or a negative `:Time`), `param` `:Param` 0-5: the table
/// shake's size across and down (pixels at ±100 of the path), the swing's
/// sizes across and down, and its half-waves over `time` across and down.
pub struct Quake {
    pub time: i32,
    pub fade: i32,
    pub looped: bool,
    pub param: [f32; 6],
}

/// ease_value (0x8103cc18) at power 1, from 0 to 1 (`from` 1 runs it back).
fn ease(from: f32, t: f32, kind: u8) -> f32 {
    let to = 1.0 - from;
    let d = to - from;
    let v = match kind {
        1 => (t * 1000.0 * t * 1000.0 * 0.001) / 1000.0,
        2 => 1.0 - (1.0 - (1.0 - (1.0 - t) * (1.0 - t))),
        3 if t < 0.5 => t * 4.0 * t * 0.25 * 2.0,
        3 => 1.0 - (1.0 - t) * 4.0 * (1.0 - t) * 2.0 * 0.25,
        _ => t,
    };
    from + d * v
}

impl Quake {
    /// The offsets (x, y) of each update while it runs (at most `n`).
    pub fn frames(&self, n: usize) -> Vec<(i32, i32)> {
        let [ax, ay, sx, sy, hx, hy] = self.param;
        let (mut frame, mut counter, mut faded, mut first) = (0, 0, 0, true);
        let mut out = Vec::new();
        while out.len() < n {
            frame += 1;
            // the swing reads this update's frame before the wrap
            let now = frame;
            if self.time < frame {
                if !self.looped {
                    break;
                }
                first = false;
                frame -= self.time;
            }
            if self.fade >= 1 {
                faded += 1;
                if faded >= self.fade {
                    break;
                }
            }
            let left = |v: f32| if self.fade > 0 { v * (self.fade - faded) as f32 / self.fade as f32 } else { v };
            let (mut x, mut y) = (0.0f32, 0.0f32);
            if ax != 0.0 || ay != 0.0 {
                counter += 1;
                if counter > 100 {
                    counter -= 100;
                }
                let t = (counter as f32 * 6.0) as i32;
                let (frac, seg) = (t % 10, (t % 100) / 10);
                // 0x81008a3c: a point on a whole step stays at 0
                if frac > 0 {
                    let next = (seg as usize + 1) % 10;
                    let at = |p: &[i32; 11]| p[seg as usize] as f32 + ((p[next] - p[seg as usize]) * frac / 10) as f32;
                    x = left(at(&PATH_X) * (ax / 100.0));
                    y = left(at(&PATH_Y) * (ay / 100.0));
                }
            }
            if self.time > 0 {
                let mut swing = [0.0f32; 2];
                for (i, (size, halves)) in [(sx, hx), (sy, hy)].into_iter().enumerate() {
                    if halves <= 0.0 {
                        continue;
                    }
                    let period = (self.time as f32 / halves) as i32;
                    if period <= 0 {
                        continue;
                    }
                    let (k, f) = (now / period, (now % period) as f32 / period as f32);
                    let last = k as f32 >= halves - 1.0 && f >= 0.5;
                    let odd = self.looped && halves as i32 % 2 == 1;
                    // in and out: the first half-wave's rise (every one
                    // of a loop's later passes with an odd count) and the
                    // last one's fall; else out to the size, in back
                    let kind = if ((first || odd) && k == 0 && f < 0.5) || ((!self.looped || odd) && last) {
                        3
                    } else if f < 0.5 {
                        2
                    } else {
                        1
                    };
                    let v = if f < 0.5 { ease(0.0, f * 2.0, kind) } else { ease(1.0, (f - 0.5) * 2.0, kind) };
                    swing[i] += size * if k % 2 == 1 { -v } else { v };
                }
                x += left(swing[0]);
                y += left(swing[1]);
            }
            out.push((x as i32, y as i32));
        }
        out
    }
}

